import { existsSync, writeFileSync } from "node:fs";
import { randomBytes } from "node:crypto";
import { loadLocalEnv } from "./env";

function secret(bytes = 32): string {
  return randomBytes(bytes).toString("base64");
}

function base32Secret(): string {
  const alphabet = "ABCDEFGHIJKLMNOPQRSTUVWXYZ234567";
  const bytes = randomBytes(20);
  let bits = 0;
  let value = 0;
  let output = "";
  for (const byte of bytes) {
    value = (value << 8) | byte;
    bits += 8;
    while (bits >= 5) {
      output += alphabet[(value >>> (bits - 5)) & 31];
      bits -= 5;
    }
  }
  if (bits > 0) output += alphabet[(value << (5 - bits)) & 31];
  return output;
}

function ensureLocalEnv(): { created: boolean; password?: string } {
  if (existsSync(".env.local")) {
    loadLocalEnv();
    return { created: false };
  }

  const password = `Demo-${randomBytes(9).toString("base64url")}`;
  const content = `# Generated by npm run db:setup for LOCAL DEMO use only.
# Never commit this file. It is ignored by .gitignore.
SITE_URL=http://localhost:3000
APP_ENV=local
DEMO_MODE=true
SEED_DEMO_DATA=true
PGLITE_DATA_DIR=.pglite
AUTH_SECRET=${secret(48)}
ACTIVATION_KEK_V1=${secret(32)}
ACTIVATION_KEK_ACTIVE_VERSION=1
MOCK_PAYMENT_WEBHOOK_SECRET=${secret(32)}
INTERNAL_JOB_SECRET=${secret(32)}
CRON_SECRET=${secret(32)}
RATE_LIMIT_HASH_SECRET=${secret(32)}
DEMO_ADMIN_EMAIL=admin@demo.local
DEMO_ADMIN_PASSWORD=${password}
DEMO_ADMIN_TOTP_SECRET=${base32Secret()}
PAYMENTS_LIVE_ENABLED=false
SUPPLIER_LIVE_ENABLED=false
EMAIL_LIVE_ENABLED=false
`;
  writeFileSync(".env.local", content, { encoding: "utf8", mode: 0o600 });
  loadLocalEnv();
  return { created: true, password };
}

async function main(): Promise<void> {
  loadLocalEnv();
  const deployedContext = (process.env.APP_ENV || "local").toLowerCase();
  if (
    process.env.NETLIFY === "true" ||
    ["preview", "staging", "production"].includes(deployedContext)
  ) {
    throw new Error(
      "db:setup is local-only. Configure Netlify environment variables and run db:migrate against the deployed database instead.",
    );
  }
  const { created, password } = ensureLocalEnv();
  const { createDatabase } = await import("@/lib/db/client");
  const { runMigrations } = await import("@/lib/db/migrate");
  const { seedDemoData } = await import("@/lib/db/seed");

  const handle = await createDatabase({
    dataDir: process.env.PGLITE_DATA_DIR || ".pglite",
    connectionString: "",
  });

  try {
    await runMigrations(handle.client, handle.dialect);
    const result = await seedDemoData(handle.db);
    console.log("eSIMprove local setup complete.");
    console.log(`Database: ${handle.dialect} (${process.env.PGLITE_DATA_DIR || ".pglite"})`);
    console.log(
      `Demo catalogue: ${result.regions} regions, ${result.destinations} destinations, ${result.plans} plans.`,
    );
    console.log("All catalogue rows are marked demo and are not real supplier data.");
    console.log(`Demo admin: ${process.env.DEMO_ADMIN_EMAIL || "admin@demo.local"}`);
    if (created && password) {
      console.log("DEMO ONLY — generated admin password is stored in .env.local.");
    } else {
      console.log("Using existing .env.local; demo credentials were not changed.");
    }
    console.log("Run `npm run totp` for the current demo admin TOTP code.");
    console.log("Live payments, supplier orders, and email sending remain disabled.");
  } finally {
    await handle.close();
  }
}

main().catch((error) => {
  console.error("Setup failed:", error instanceof Error ? error.message : error);
  process.exitCode = 1;
});
